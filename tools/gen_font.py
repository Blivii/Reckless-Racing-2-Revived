#!/usr/bin/env python3
"""Renders ASCII 32..126 from DejaVu Sans Mono Bold into a 1-bit 16x6 glyph atlas for the
overlay, written as src/font.inc. Cell 95 (char 127) is solid, for drawing filled boxes.
Usage: gen_font.py [font.ttf] > src/font.inc"""
import sys
from PIL import Image, ImageDraw, ImageFont

CW, CH, SIZE = 10, 16, 14
font = ImageFont.truetype(sys.argv[1] if len(sys.argv) > 1 else
                          "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf", SIZE)
atlas = Image.new("L", (16 * CW, 6 * CH), 0)
draw = ImageDraw.Draw(atlas)
for i in range(96):
    x, y = (i % 16) * CW, (i // 16) * CH
    if i == 95:
        draw.rectangle([x, y, x + CW - 1, y + CH - 1], fill=255)
    else:
        draw.text((x + CW / 2, y + CH / 2 + 1), chr(32 + i), font=font, fill=255, anchor="mm")
bits = bytearray((atlas.width * atlas.height + 7) // 8)
for p, v in enumerate(atlas.tobytes()):
    if v >= 128:
        bits[p >> 3] |= 1 << (p & 7)
print(f"// generated by tools/gen_font.py: {atlas.width}x{atlas.height}, 1 bit per pixel, LSB first")
print(f"constexpr int kFontCellW = {CW}, kFontCellH = {CH}, kFontW = {atlas.width}, kFontH = {atlas.height};")
print("static const unsigned char kFontBits[] = {")
for i in range(0, len(bits), 24):
    print("    " + ", ".join(f"0x{b:02x}" for b in bits[i:i + 24]) + ",")
print("};")
if "--preview" in sys.argv:
    atlas.point(lambda v: 255 if v >= 128 else 0).resize((atlas.width * 3, atlas.height * 3), Image.NEAREST).save("font_preview.png")
